#!/usr/bin/env python3
"""Generate src/drivers/font8x16.c, an 8x16 1-bit ASCII font.

Renders DejaVu Sans Mono (Bitstream Vera license, see the comment in the
output) with Pillow and thresholds it. Run again to change size or font:

    python3 tools/genfont.py /usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf > src/drivers/font8x16.c
"""

import sys

from PIL import Image, ImageDraw, ImageFont

W, H = 8, 16
FIRST, LAST = 0x20, 0x7E
BASELINE = 12  # rows 0-11 above the baseline, 12-15 for descenders


def main() -> int:
    font = ImageFont.truetype(sys.argv[1], 14)
    ascent, _ = font.getmetrics()
    rows_out = []
    for code in range(FIRST, LAST + 1):
        img = Image.new("L", (W, H), 0)
        ImageDraw.Draw(img).text((0, BASELINE - ascent), chr(code), font=font, fill=255)
        rows = []
        for y in range(H):
            bits = 0
            for x in range(W):
                if img.getpixel((x, y)) >= 110:
                    bits |= 0x80 >> x
            rows.append(bits)
        label = chr(code) if chr(code) not in "\\'" else "\\" + chr(code)
        rows_out.append("    /* '%s' */ %s," % (label, ", ".join("0x%02x" % r for r in rows)))

    print("/*")
    print(" * 8x16 ASCII font, generated by tools/genfont.py from DejaVu Sans Mono.")
    print(" * DejaVu fonts are based on Bitstream Vera; see https://dejavu-fonts.github.io/License.html")
    print(" * Each glyph is 16 rows, one byte per row, MSB is the leftmost pixel.")
    print(" */")
    print('#include "font.h"')
    print()
    print("const uint8_t font8x16[%d][16] = {" % (LAST - FIRST + 1))
    for line in rows_out:
        print(line.replace(" */ ", " */ {", 1).rstrip(",") + "},")
    print("};")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
